async def age_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Handle age selection. Filter games and display results.
    """
    query = update.callback_query
    await query.answer()
    data = query.data

    if data == "age_skip":
        context.user_data['age'] = None
    else:
        context.user_data['age'] = data.split('_')[1]

    players = context.user_data.get('players')
    duration = context.user_data.get('duration')
    age = context.user_data.get('age')

    filtered_games = bot.filter_games(players, duration, age)

    if not filtered_games:
        await query.delete_message()
        await update.effective_chat.send_message(
            "❌ *Не нашлось игр под ваши критерии.*\n\nНажмите /start для нового поиска",
            parse_mode='Markdown'
        )
        return ConversationHandler.END

    context.user_data['filtered_games'] = filtered_games
    context.user_data['current_index'] = 0
    await query.delete_message()
    await show_game(update, context)
    return ConversationHandler.END


async def show_game(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Display current game with navigation buttons.
    """
    filtered_games = context.user_data.get('filtered_games', [])
    current_index = context.user_data.get('current_index', 0)

    if not filtered_games:
        return

    game = filtered_games[current_index]
    total = len(filtered_games)

    keyboard = []
    nav_buttons = []

    if current_index > 0:
        nav_buttons.append(InlineKeyboardButton("◀️ Предыдущая", callback_data="prev_game"))
    if current_index < total - 1:
        nav_buttons.append(InlineKeyboardButton("Следующая ▶️", callback_data="next_game"))

    if nav_buttons:
        keyboard.append(nav_buttons)

    keyboard.append([InlineKeyboardButton("🔄 Новый поиск", callback_data="new_search")])
    reply_markup = InlineKeyboardMarkup(keyboard)

    message_text = bot.format_game_message(game, current_index + 1, total)

    if 'last_message_id' in context.user_data:
        try:
            await context.bot.edit_message_text(
                chat_id=update.effective_chat.id,
                message_id=context.user_data['last_message_id'],
                text=message_text,
                parse_mode='Markdown',
                disable_web_page_preview=True,
                reply_markup=reply_markup
            )
        except:
            msg = await update.effective_chat.send_message(
                message_text,
                parse_mode='Markdown',
                disable_web_page_preview=True,
                reply_markup=reply_markup
            )
            context.user_data['last_message_id'] = msg.message_id
    else:
        if update.callback_query:
            msg = await update.callback_query.message.reply_text(
                message_text,
                parse_mode='Markdown',
                disable_web_page_preview=True,
                reply_markup=reply_markup
            )
        else:
            msg = await update.effective_chat.send_message(
                message_text,
                parse_mode='Markdown',
                disable_web_page_preview=True,
                reply_markup=reply_markup
            )
        context.user_data['last_message_id'] = msg.message_id


async def navigation_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Handle navigation between games and new search requests.
    """
    query = update.callback_query
    await query.answer()
    action = query.data

    if action == "prev_game":
        context.user_data['current_index'] -= 1
        await show_game(update, context)
    elif action == "next_game":
        context.user_data['current_index'] += 1
        await show_game(update, context)
    elif action == "new_search":
        await query.message.reply_text("/start")


async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Handle cancel command. Clear user data and end conversation.
    """
    if update.callback_query:
        query = update.callback_query
        await query.answer()
        await query.message.delete()
        await query.message.reply_text("❌ Поиск отменен.\nНажмите /start для нового поиска")
    else:
        await update.message.reply_text("❌ Поиск отменен.\nНажмите /start для нового поиска")
    context.user_data.clear()
    return ConversationHandler.END


async def main():
    """
    Initialize and start the bot application.
    """
    app = Application.builder().token(TOKEN).build()

    conv_handler = ConversationHandler(
        entry_points=[CommandHandler('start', start)],
        states={
            PLAYERS: [CallbackQueryHandler(players_handler, pattern='^players_')],
            DURATION: [CallbackQueryHandler(duration_handler, pattern='^duration_')],
            AGE: [CallbackQueryHandler(age_handler, pattern='^age_')],
        },
        fallbacks=[
            CommandHandler('start', start),
            CommandHandler('cancel', cancel),
        ],
        allow_reentry=True,
    )

    app.add_handler(conv_handler)
    app.add_handler(CallbackQueryHandler(navigation_handler, pattern='^(prev_game|next_game|new_search)$'))

    print("Bot is ready")

    await app.initialize()
    await app.start()
    await app.updater.start_polling()

    return app


