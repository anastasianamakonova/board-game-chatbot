class BoardGameBot:
    """
    Main bot class for loading and filtering board games data.
    """

    def __init__(self):
        """Initialize bot and load games data from JSON file."""
        self.games = self.load_games()

    def load_games(self) -> List[Dict]:
        """
        Load board games data from JSON file.
        """
        if not GAMES_PATH.exists():
            print(f"File {GAMES_PATH} not found")
            return []

        with open(GAMES_PATH, 'r', encoding='utf-8') as f:
            games = json.load(f)
        print(f"Loaded {len(games)} games")
        return games

    def parse_players(self, players_str: str) -> Optional[tuple]:
        """
        Parse player count string into min and max players.
        """
        if not players_str:
            return None
        match = re.search(r'(\d+)\s*[-–]\s*(\d+)', str(players_str))
        if match:
            return (int(match.group(1)), int(match.group(2)))
        match = re.search(r'(\d+)', str(players_str))
        if match:
            num = int(match.group(1))
            return (num, num)
        return None

    def parse_duration(self, duration_str: str) -> Optional[int]:
        """
        Parse game duration from string.
        """
        if not duration_str:
            return None
        match = re.search(r'(\d+)', str(duration_str))
        if match:
            return int(match.group(1))
        return None

    def parse_age(self, age_str: str) -> Optional[int]:
        """
        Parse age restriction from string.
        """
        if not age_str:
            return None
        match = re.search(r'(\d+)\+', str(age_str))
        if match:
            return int(match.group(1))
        match = re.search(r'(\d+)', str(age_str))
        if match:
            return int(match.group(1))
        return None

    def check_age_match(self, game_age: Optional[int], user_age_category: int) -> bool:
        """
        Check if game age matches user age category.
        """
        if game_age is None:
            return True
        if user_age_category == 6:
            return 6 <= game_age <= 11
        elif user_age_category == 12:
            return 12 <= game_age <= 17
        elif user_age_category == 18:
            return game_age >= 18
        return True

    def filter_games(self, players_req: Optional[str], duration_req: Optional[str], age_req: Optional[str]) -> List[Dict]:
        """
        Filter games based on user requirements.
        """
        filtered = []
        players_num = None
        players_is_plus = False
        if players_req and players_req != 'skip':
            if players_req == '8+':
                players_num = 8
                players_is_plus = True
            else:
                players_num = int(players_req)
                players_is_plus = False

        duration_max = None
        if duration_req and duration_req != 'skip':
            duration_max = int(duration_req)

        age_category = None
        if age_req and age_req != 'skip':
            age_category = int(age_req.replace('+', ''))

        for game in self.games:
            if players_num:
                game_players = self.parse_players(game.get('players', ''))
                if game_players:
                    game_min, game_max = game_players
                    if players_is_plus:
                        if game_max < players_num:
                            continue
                    else:
                        if not (game_min <= players_num <= game_max):
                            continue
                else:
                    continue

            if duration_max:
                game_duration = self.parse_duration(game.get('duration', ''))
                if game_duration and game_duration > duration_max:
                    continue

            if age_category is not None:
                game_age = self.parse_age(game.get('age', ''))
                if not self.check_age_match(game_age, age_category):
                    continue

            filtered.append(game)

        return filtered

    def format_game_message(self, game: Dict, index: int, total: int) -> str:
        """
        Format game information for display.
        """
        description = game.get('description', '')
        return f"""
🎲 *[{index}/{total}]*

*{game['title']}*

👥 *Игроки:* {game['players'] if game['players'] else 'не указано'}
⏱ *Время:* {game['duration'] if game['duration'] else 'не указано'} мин
📅 *Возраст:* {game['age'] if game['age'] else 'не указано'}
🎭 *Жанр:* {game['genre'] if game['genre'] else 'не указано'}
💰 *Цена:* {game['price'] if game['price'] else 'не указано'} руб

📝 *Описание:*
{description}
"""


